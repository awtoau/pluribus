#!/usr/bin/env python3.15t
"""Generate licensed Altera DSP IP variants (ip-generate, plain VHDL/SV) into tmp/sig/<name>/ip + sig.toml (never committed), #165.

  python3.15t scripts/cycloneiv_clean_sig_ipgen.py [NAME ...]      (default: all in CONFIGS)
Output is the unmodified ip-generate result for Quartus Lite evaluation; no licence handling of any kind.
Netlist flow: cycloneiv_clean_sig_netlist.py.  Log: tmp/logs/cycloneiv_clean_sig_ipgen.log.
"""
import shutil
import subprocess
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO / "scripts"))
import toolchain  # noqa: E402

SIG = REPO / "tmp" / "sig"
LOG = REPO / "tmp" / "logs" / "cycloneiv_clean_sig_ipgen.log"
IG = Path(toolchain.quartus_bin()).parent / "sopc_builder" / "bin" / "ip-generate"
GEN_LIMIT_S = 120      # stall guard dominates; ip-generate runs 1-10 s here (bch generator poly ~7 s) -> backstop >10x
FAMILY = "Cyclone IV GX"


def fft(length, flow, width, out, twid=None, **kw):
    p = dict(length=length, data_flow=flow, data_rep="Fixed Point", in_width=width, out_width=out, twid_width=twid or width)
    p.update(kw)
    return "altera_fft_ii", p


# name -> (component, params)
CONFIGS = {
    "fft_vs256_12": fft(256, "Variable Streaming", 12, 20),
    "fft_vs256_16": fft(256, "Variable Streaming", 16, 24),
    "fft_st64_16": fft(64, "Streaming", 16, 22, data_rep="Block Floating Point", out_order="Natural"),
    "fft_b64_16": fft(64, "Burst", 16, 22, data_rep="Block Floating Point", out_order="Natural"),
    "fft_bb64_16": fft(64, "Buffered Burst", 16, 22, data_rep="Block Floating Point", out_order="Natural"),
    "nco_small_rom": ("altera_nco_ii", dict(arch="small_rom", apr=24, apri=12, mpr=12)),
    "nco_cordic": ("altera_nco_ii", dict(arch="cordic", apr=24, mpr=12)),
    "nco_large_nodither": ("altera_nco_ii", dict(arch="large_rom", apr=24, apri=12, mpr=12, want_dither="false")),
    "cic_dec_s3_r8": ("altera_cic_ii", dict(FILTER_TYPE="decimator", STAGES=3, D_DELAY=1, RCF_FIX=8, IN_WIDTH=16)),
    "cic_dec_s5_r16": ("altera_cic_ii", dict(FILTER_TYPE="decimator", STAGES=5, D_DELAY=1, RCF_FIX=16, IN_WIDTH=16)),
    "cic_int_s4_r8": ("altera_cic_ii", dict(FILTER_TYPE="interpolator", STAGES=4, D_DELAY=1, RCF_FIX=8, IN_WIDTH=12)),
    "rs_enc_204_188": ("altera_rs_ii", dict(RS="Encoder", N=204, CHECK=16)),
    "rs_dec_255_239": ("altera_rs_ii", dict(RS="Decoder", N=255, CHECK=16)),
    "rs_dec_204_188": ("altera_rs_ii", dict(RS="Decoder", N=204, CHECK=16)),
    "bch_enc_255_239": ("altera_bch", dict(BCH="Encoder", M_BITS=8, N_BITS=255, T_BITS=2, PARITY_BITS=16, K_BITS=239, IRRPOL=285, DATA_WIDTH=8)),
    "bch_enc_255_191": ("altera_bch", dict(BCH="Encoder", M_BITS=8, N_BITS=255, T_BITS=8, PARITY_BITS=64, K_BITS=191, IRRPOL=285, DATA_WIDTH=8)),
    "bch_dec_255_191": ("altera_bch", dict(BCH="Decoder", M_BITS=8, N_BITS=255, T_BITS=8, PARITY_BITS=64, K_BITS=191, IRRPOL=285, DATA_WIDTH=8)),
    # K=7 171/133 octal = 121/91 decimal; softbits 1 = hard decision
    "vit_k7_hard": ("altera_vit_ii", dict(viterbi_type="Parallel", n=2, L=7, ga=121, gb=91, softbits=1, v=35)),
    "vit_k7_soft3": ("altera_vit_ii", dict(viterbi_type="Parallel", n=2, L=7, ga=121, gb=91, softbits=3, v=35)),
    "vit_k7_hybrid": ("altera_vit_ii", dict(viterbi_type="Hybrid", n=2, L=7, ga=121, gb=91, softbits=3, v=35, acs_units=4)),
}


def gen(name, log):
    comp, params = CONFIGS[name]
    d = SIG / name
    shutil.rmtree(d, ignore_errors=True)
    (d / "ip").mkdir(parents=True)
    cmd = [str(IG), f"--component-name={comp}", f"--output-name=u_{name}", "--output-directory=ip",
           "--file-set=QUARTUS_SYNTH", f"--report-file=qip:ip/u_{name}.qip", f"--system-info=DEVICE_FAMILY={FAMILY}",
           "--remove-qsys-generate-warning"]
    if comp == "altera_vit_ii":
        cmd.append(f"--component-file={IG.parent.parent.parent.parent}/ip/altera/dsp/altera_vit_ii/top_hw/altera_viterbi_ii_hw.tcl")
        cmd.remove(f"--component-name={comp}")
    for k, v in params.items():
        cmd.append(f"--component-parameter={k}={v}")
    r = subprocess.run(cmd, cwd=d, capture_output=True, text=True, timeout=GEN_LIMIT_S)
    (d / "gen.log").write_text(r.stdout + r.stderr)
    if r.returncode:
        log.write(f"{name}: FAIL rc={r.returncode} {(r.stdout + r.stderr).strip().splitlines()[-1:]}\n")
        return False
    top = f"u_{name}"
    (d / "sig.toml").write_text(f'top = "{top}"\nfiles = ["ip/{top}.qip"]\nparams = "{comp} {params}"\n'.replace("'", ""))
    (d / "LICENCE-NOTE.txt").write_text(f"Altera {comp} generated by Quartus SC Lite ip-generate, Quartus-side netlist oracle only; not redistributed.\n")
    log.write(f"{name}: ok {comp} {params}\n")
    return True


def main():
    LOG.parent.mkdir(parents=True, exist_ok=True)
    with open(LOG, "a") as log:
        for n in (sys.argv[1:] or CONFIGS):
            ok = gen(n, log)
            log.flush()
            print(n, "ok" if ok else "FAIL", flush=True)


if __name__ == "__main__":
    main()
