#!/usr/bin/env python3.15t
"""Write docs/machxo2-coverage-designs.md from corpus/machxo2/coverage outputs (facts only).

Sections: builds (ok/failed + exact reasons), placement honoured (requested LOCATE vs ncdread),
coverage before/after (machxo2_oracle_coverage.py), oracle comparison of the new designs
(headline with raw fault counts, pip/net/gkey verdicts), per-rule status of the three
never-exercised lifter rules, per-profile fault counts.

Usage: python3.15t scripts/machxo2_coverage_report.py [--dir D] [--old D] [--out FILE]
Log:   tmp/logs/machxo2_coverage_report.log
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tomllib
from collections import Counter, defaultdict

SCRIPTS = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(SCRIPTS)
NEW = os.path.join(REPO, "corpus", "machxo2", "coverage")
OLD = "/mnt/2tb/git/pluribus/corpus/machxo2/diamond-fuzz"
OUT = os.path.join(REPO, "docs", "machxo2-coverage-designs.md")


def cov(corpora, device):
    # 120 s: coverage over 2.8k decoded configs measured 1 s warm (2026-10-24); x120 for a cold cache. Expiry: raise.
    r = subprocess.run([sys.executable, os.path.join(SCRIPTS, "machxo2_oracle_coverage.py"), "--corpus", *corpora]
                       + (["--device", device] if device else []), capture_output=True, text=True, timeout=120)
    return [re.sub(r"^\S+ \S+ ", "", ln) for ln in (r.stdout + r.stderr).splitlines() if ln.strip()]


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--dir", default=NEW)
    ap.add_argument("--old", default=OLD)
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    names = sorted(n for n in os.listdir(a.dir) if os.path.exists(os.path.join(a.dir, n, "design.toml")))
    L = []
    w = L.append
    rows = []
    for n in names:
        d = os.path.join(a.dir, n)
        meta = tomllib.load(open(os.path.join(d, "design.toml"), "rb"))
        bj = json.load(open(os.path.join(d, "build.json"))) if os.path.exists(os.path.join(d, "build.json")) else {"status": "not built"}
        rows.append((n, meta, bj, d))
    ok = [r for r in rows if r[2].get("status") == "ok"]
    w("# MachXO2 coverage-driven designs\n")
    w("Generated by `scripts/machxo2_coverage_report.py` (not edited by hand). Designs: `scripts/machxo2_coverage_gen.py`; build: `scripts/machxo2_construct_build.py --dir corpus/machxo2/coverage`.")
    w("Lane = input pad -> `FD1S3AX` (LOCATEd slice) -> `FD1S3AX` (LOCATEd slice) -> output pad; pads and sites chosen per profile. Device LCMXO2-1200HC-5TG100C.\n")
    w(f"- Builds: {len(rows)} attempted, {len(ok)} succeeded, {len(rows) - len(ok)} failed.")
    fails = defaultdict(list)
    for n, m, b, d in rows:
        if b.get("status") != "ok":
            fails[(b.get("reason") or b.get("status", "")).strip()[:300]].append(n)
    for reason, ns in sorted(fails.items(), key=lambda x: -len(x[1])):
        w(f"  - {len(ns)} failed: `{reason}` ({', '.join(ns[:12])}{' ...' if len(ns) > 12 else ''})")
    # placement honoured
    req = hit = 0
    for n, m, b, d in ok:
        lpf = open(os.path.join(d, "placement.lpf")).read()
        want = dict(re.findall(r'LOCATE COMP "(f[12]_\d+)" SITE "(\w+)"', lpf))
        o = json.load(open(os.path.join(d, "oracle.json")))
        # slice prims -> instance names live in comp "prims" REG fields
        got = {}
        for c in o["comps"]:
            if c["type"] == "SLICE":
                for k, v in c["prims"].items():
                    if k.startswith("REG"):
                        got[v] = c["site"]
        for inst, site in want.items():
            req += 1
            g = [s for nm, s in got.items() if nm.endswith(inst) or inst in nm]
            if g and g[0][:-1] == site[:-1]:
                hit += 1
    w(f"- Register placement honoured (slice tile R#C# equal; slot may differ): {hit} / {req} requested sites.\n")
    # coverage
    w("## Coverage before / after (connections = tile-type `.mux` sources in device-db bits.db, exercised = `arc:` in a decoded.config)\n")
    for label, cor, dev in (("all 73 routed tile types in the DB (all devices)", None, None),
                            ("types present on LCMXO2-1200 only", None, "LCMXO2-1200")):
        w(f"### {label}\n")
        for tag, cs in (("before (2779 existing designs)", [a.old]), ("after (existing + new)", [a.old, a.dir])):
            lines = cov(cs, dev)
            w(f"- {tag}:")
            for ln in lines[:6]:
                w(f"  - {ln}")
        w("")
    # comparison
    w("## Oracle comparison of the new designs\n")
    cs = os.path.join(a.dir, "_compare_summary.json")
    if not os.path.exists(cs):
        w("- not run (untested)")
    else:
        s = json.load(open(cs))
        w(f"- targets {s['targets']}, status {s['status']}")
        for k, h in s.get("headline", {}).items():
            w(f"- {k}: {h['match']} / {h['total']} matched = {h['rate_pct']}%; faults (every non-MATCH) {h['faults']}")
        w(f"- pips by verdict: {s['pips']}")
        w(f"- nets by verdict: {s['net_verdicts']}")
        w("\n### Fault categories (pips)\n")
        for k, v in sorted(s["pip_detail"].items()):
            if k.startswith("MATCH"):
                continue
            w(f"- `{k}`: {sum(v.values())} (top: {dict(list(v.items())[:6])})")
        w("\n### gkey branches (AGREE / DISAGREE with Diamond)\n")
        for k, v in sorted(s["gkey_verdicts"].items()):
            w(f"- `{k}`: {v}")
        w("\n### Three never-exercised rules\n")
        gv = s["gkey_verdicts"]
        for rule in ("h06e_right_mirror", "right_stub_drop", "h06w_left_mirror"):
            hits = {k: v for k, v in gv.items() if k.startswith(rule + ":")}
            w(f"- `{rule}`: {hits if hits else 'not exercised by any new design (untested)'}")
        w("- `_v02_alias`: see below.")
        by = defaultdict(Counter)
        prof = {n: m.get("profile") for n, m, b, d in rows}
        for n, m, b, d in ok:
            cj = os.path.join(d, "compare.json")
            if os.path.exists(cj):
                c = json.load(open(cj))
                tot = sum(c["pips"].values())
                by[prof[n]].update({"designs": 1, "pips": tot, "pip_faults": tot - c["pips"].get("MATCH", 0),
                                    "nets": sum(c["net_verdicts"].values()),
                                    "net_faults": sum(c["net_verdicts"].values()) - c["net_verdicts"].get("MATCH", 0)})
        w("\n### Per profile\n")
        w("| profile | designs | pips | pip faults | nets | net faults |")
        w("|---|---|---|---|---|---|")
        for p, c in sorted(by.items()):
            w(f"| {p} | {c['designs']} | {c['pips']} | {c['pip_faults']} | {c['nets']} | {c['net_faults']} |")
    os.makedirs(os.path.dirname(a.out), exist_ok=True)
    open(a.out, "w").write("\n".join(L) + "\n")
    print("wrote", a.out)


if __name__ == "__main__":
    main()
