#!/usr/bin/env python3.15t
"""Field-by-field summary of one lifted label, and a diff between two summaries.

Regression gate for lifter changes: dump before, change, re-run, diff.  Any
changed field is shown; nothing is summarised away.

    scripts/lift_summary.py --label V07 --out tmp/summary_V07_before.json
    scripts/lift_summary.py --label V07 --diff tmp/summary_V07_before.json

DB from $PLURIBUS_SQLITE_PATH.  Gate numbers are parsed from
tmp/pipeline_<label>_verify.log (check_verilog.py), the emitted .v from out/.
Logs to tmp/logs/lift_summary.log.
"""
import argparse
import hashlib
import json
import logging
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO))
from sqlalchemy import text  # noqa: E402
import db  # noqa: E402

LOG = REPO / "tmp/logs/lift_summary.log"
COUNT_TABLES = [
    "luts", "ffs", "nets", "net_fanout", "pad_map", "efb_config",
    "ebr_init_blocks", "const_nets", "clock_domain_summary",
    "arcs", "cdc_synchronisers", "patterns",
]
# Same JSON keys as before the hard_cell_ports merge (phase F step 4) so old summaries diff.
COUNT_FILTERED = {
    "efb_ports": "hard_cell_ports where bitstream=:b and cell='EFB'",
    "ebr_ports": "hard_cell_ports where bitstream=:b and cell<>'EFB'",
}


def summarise(label):
    s = {"label": label}
    with db.engine().connect() as c:
        row = c.execute(text("select id from bitstreams where label=:l"),
                        {"l": label}).fetchone()
        if not row:
            db.die(f"label {label} not in DB")
        b = row[0]
        for t in COUNT_TABLES:
            s[f"n_{t}"] = c.execute(
                text(f"select count(*) from {t} where bitstream=:b"),
                {"b": b}).scalar()
        for k, where in COUNT_FILTERED.items():
            s[f"n_{k}"] = c.execute(text(f"select count(*) from {where}"), {"b": b}).scalar()
        s["efb_in"] = c.execute(text(
            "select count(*) from hard_cell_ports where bitstream=:b and cell='EFB' and direction='in'"),
            {"b": b}).scalar()
        s["efb_out"] = c.execute(text(
            "select count(*) from hard_cell_ports where bitstream=:b and cell='EFB' and direction='out'"),
            {"b": b}).scalar()
        # FF D faults (#113): unresolved D (d_fault) and every constant-literal D
        s["n_ffs_d_unresolved"] = c.execute(text(
            "select count(*) from ffs where bitstream=:b and d_fault is not null"),
            {"b": b}).scalar()
        s["n_ffs_d_const"] = c.execute(text(
            "select count(*) from ffs where bitstream=:b and d like '1''b%'"),
            {"b": b}).scalar()
        # undriven = net with no driving LUT/FF/EFB output and no pad input
        s["db_undriven_nets"] = c.execute(text("""
            select count(*) from nets n where n.bitstream=:b
            and n.name not in (select z from luts where bitstream=:b and z is not null)
            and n.name not in (select q from ffs where bitstream=:b and q is not null)
            and n.name not in (select out_net from net_fanout where bitstream=:b
                               and out_net is not null)
            and n.name not in (select net_in from pad_map where bitstream=:b
                               and net_in is not null)
            and n.name not in (select net from hard_cell_ports where bitstream=:b
                               and cell='EFB' and direction='out')"""), {"b": b}).scalar()
    v = REPO / f"tmp/pipeline_{label}_verify.log"
    if v.is_file():
        t = v.read_text()
        for key, pat in [("gate_no_driver", r"no-driver.*?:\s*(\d+)"),
                         ("gate_conflicts", r"conflicting-driver\s*:\s*(\d+)"),
                         ("gate_reg_loops", r"latch/reg loops.*?:\s*(\d+)"),
                         ("gate_comb_loops", r"combinational loops\s*:\s*(\d+)"),
                         ("gate_other_warn", r"other warnings\s*:\s*(\d+)"),
                         ("gate_errors", r"errors\s*:\s*(\d+)")]:
            m = re.search(pat, t)
            s[key] = int(m.group(1)) if m else None
        s["gate_pass"] = bool(re.search(r"^PASS", t, re.M))
        for m in re.finditer(r"^\s+(\d+)\s+(\$?\w+)\s*$", t, re.M):
            s[f"cells_{m.group(2)}"] = int(m.group(1))
    for sj in sorted((REPO / f"tmp/sim/{label}").glob("summary*.json")):
        for k, v in json.loads(sj.read_text()).items():
            if k not in ("label", "pll"):
                s[f"{sj.stem}_{k}"] = v
    vf = REPO / f"out/{label}.v"
    if vf.is_file():
        # the emitter stamps its run time on line 2; hash without it
        body = [ln for ln in vf.read_text().splitlines() if "Generated by verilog.py at" not in ln]
        s["v_sha256_norm"] = hashlib.sha256("\n".join(body).encode()).hexdigest()
        s["v_bytes"] = vf.stat().st_size
    return s


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--label", required=True)
    ap.add_argument("--out")
    ap.add_argument("--diff", help="earlier summary JSON to compare against")
    a = ap.parse_args()
    LOG.parent.mkdir(parents=True, exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(message)s",
                        handlers=[logging.StreamHandler(sys.stdout),
                                  logging.FileHandler(LOG)])
    log = logging.getLogger("lift_summary")
    s = summarise(a.label)
    if a.out:
        Path(a.out).write_text(json.dumps(s, indent=1, sort_keys=True))
    if not a.diff:
        for k, v in sorted(s.items()):
            log.info("%-28s %s", k, v)
        return 0
    old = json.loads(Path(a.diff).read_text())
    changed = 0
    for k in sorted(set(old) | set(s)):
        if old.get(k) != s.get(k):
            changed += 1
            log.info("CHANGED %-26s %s -> %s", k, old.get(k), s.get(k))
    log.info("%d field(s) changed of %d", changed, len(set(old) | set(s)))
    return 0


if __name__ == "__main__":
    sys.exit(main())
