#!/usr/bin/env python3.15t
"""AF3 single-wire engine of the third-party EP4CGX150 image: cone extraction + Verilator build (#165).  Structure only.

  python3.15t scripts/cycloneiv_clean_af3_engine.py extract --nl NL.pkl     -> tmp/af3/engine.v, engine.json
  python3.15t scripts/cycloneiv_clean_af3_engine.py build                   -> verilator model tmp/af3/obj/Vengine
The cone = the 218 FFs of the B14-clock domain + every LUT / carry output reaching them backwards, the port-A side of the two
M9K tiles 7_85 / 7_86 (engine side; the serial-loader port B is idle: initial content only) and the AF3 pad.
Cell semantics are those of lifters/cycloneiv_clean/emit.py verilog() (read-only).  Log tmp/logs/cycloneiv_clean_af3_engine.log.
"""
import argparse
import json
import logging
import os
import pickle
import subprocess
import sys

REPO = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, REPO)
OUT = os.path.join(REPO, "tmp", "af3")
LOG = os.path.join(REPO, "tmp", "logs", "cycloneiv_clean_af3_engine.log")
log = logging.getLogger("af3_engine")
ENG_CLK = "u_clkbuf_out_57_91_29_0"
TILES = ("7_85", "7_86")
# word bit j -> (tile index, o[] index): engine-side read wires (V, cycloneiv_clean_ram_loader_trace.py)
WORD_WIRE = {**{j: (0, j) for j in range(16)}, **{16 + j: (1, j) for j in range(11)}, 27: (0, 16), **{28 + j: (1, 11 + j) for j in range(3)}, 31: (0, 17)}


def cone(nl):
    ff = {f["name"]: f for f in nl.ffs}
    lut = {l["name"]: l for l in nl.luts}
    co = {f"co_{l['x']}_{l['y']}_{l['le']}": l["name"] for l in nl.luts}
    eng = sorted(f["name"] for f in nl.ffs if f["clk"] == ENG_CLK)
    roots = list(eng)
    for m in nl.m9k:
        if f"{m['x']}_{m['y']}" in TILES:
            roots += list(m["addr"]) + list(m["data"]) + [m["we_b"]]   # engine write enable = the lifter's we_b (we/we_b swapped for this pair, cycloneiv_clean_tdp_we_check.py)
    io = next(i for i in nl.ios if i["ball"] == "AF3")
    roots += [io["drv"], io["oe"]]
    seen, st, luts, leaves = set(), roots, set(), set()
    while st:
        x = st.pop()
        if x in seen or not x or x.startswith(("1'", "0'")):
            continue
        seen.add(x)
        if x in ff:
            for k in ("d", "ena", "aclr", "sclr"):
                if ff[x].get(k):
                    st.append(ff[x][k])
        elif x in lut:
            luts.add(x)
            st.extend(lut[x]["pins"])
        elif x in co:
            st.append(co[x])
            luts.add(co[x])
        else:
            leaves.add(x)
    return eng, sorted(luts), sorted(leaves), ff, lut


def sig(s):
    """netlist signal -> Verilog identifier (M9K output bit and pad become module-local names)."""
    if s.startswith("m9k_") and "_o[" in s:
        t, i = s.split("_o[")
        return f"{t}_o[{i[:-1]}]"
    return s


def extract(nl):
    os.makedirs(OUT, exist_ok=True)
    eng, luts, leaves, ff, lut = cone(nl)
    bad = [x for x in leaves if not (x.startswith("m9k_7_8") or x == "pad_AF3")]
    if bad:
        raise SystemExit(f"cone has unexpected leaves {bad}")
    io = next(i for i in nl.ios if i["ball"] == "AF3")
    m9 = {f"{m['x']}_{m['y']}": m for m in nl.m9k}
    o = ["// generated by scripts/cycloneiv_clean_af3_engine.py; cone of the B14-clock FF domain (218 FFs)",
         "module engine #(parameter PREREAD = 1, parameter WEMODE = 2, parameter WEHOLD = 0, parameter OVR = 0) (input clk, input pad_AF3, input [31:0] ovr_w0, input [31:0] ovr_w12, output af3_drv, output af3_oe, output [217:0] ffvec, output [8:0] ramaddr, output ramwe, output [31:0] ramrd, output [31:0] ramwd);"]
    for l in luts:
        L = lut[l]
        o.append(f"wire {l}; wire co_{L['x']}_{L['y']}_{L['le']};")
    for f in eng:
        o.append(f"reg {f} = 1'b0;")
    for t in TILES:
        o.append(f"wire [35:0] m9k_{t}_o;")
    for l in luts:
        L = lut[l]
        a, b, c, d = (sig(p) if p != l else "1'b0" for p in L["pins"])     # 2 LEs feed their own pin (undecoded register, ring in the netlist): self pin tied 0
        o.append(f"localparam [15:0] I_{l} = 16'h{L['init']:04X};")
        o.append(f"assign {l} = I_{l}[{{{d}, {c}, {b}, {a}}}];")
        o.append(f"assign co_{L['x']}_{L['y']}_{L['le']} = I_{l}[{{1'b0, {'1' + chr(39) + 'b0' if L['mode'] != 'cin' else c}, {b}, {a}}}];")
    for f in eng:
        F = ff[f]

        def x(key, idle):
            return idle if F.get(key) is None else (f"(~{F[key]})" if F.get(key + "_inv") else F[key])
        clrn, ena, sclr = x("aclr", "1'b1"), x("ena", "1'b1"), x("sclr", "1'b0")
        ev = "posedge clk" + (f" or negedge {clrn}" if F.get("aclr") is not None else "")
        body = f"{f} <= {sclr} ? 1'b0 : {F['d']};" if F.get("sclr") is not None else f"{f} <= {F['d']};"
        o.append(f"always @({ev}) begin" + (f" if (!{clrn}) {f} <= 1'b0; else" if F.get("aclr") is not None else "") + (f" if ({ena}) " if F.get("ena") is not None else " ") + body + " end")
    o.append("integer cyc = 0; always @(posedge clk) cyc <= cyc + 1;")
    o.append("assign ffvec = {" + ", ".join(eng) + "};")
    ta, tb = m9["7_85"], m9["7_86"]
    o.append(f"wire [8:0] ovr_ad = {{{', '.join(reversed([sig(p) for p in ta['addr']]))}}};")
    o.append(f"wire we_eff = (WEMODE != 0 && cyc >= WEHOLD) && (WEMODE == 2 ? !{ta['we_b']} : {ta['we_b']});")
    o.append("reg seen0 = 1'b0, seen12 = 1'b0;   // dummy secret replaces only the FIRST engine write of each secret word (later writes are the message schedule)")
    o.append("wire ovr_en = OVR != 0 && we_eff && ((ovr_ad == 9'h110 && !seen0) || (ovr_ad == 9'h11c && !seen12)); wire [31:0] ovr_word = (ovr_ad == 9'h110) ? ovr_w0 : ovr_w12;")
    o.append("always @(posedge clk) if (we_eff && OVR != 0) begin if (ovr_ad == 9'h110) seen0 <= 1'b1; if (ovr_ad == 9'h11c) seen12 <= 1'b1; end")
    for t, m in zip(TILES, (ta, tb)):
        n = f"m9k_{t}"
        o.append(f"reg [17:0] {n}_mem [0:511]; reg [17:0] {n}_qca;")
        o.append("initial begin " + " ".join(f"{n}_mem[{k}] = 18'h{v:X};" for k, v in enumerate(m["init"])) + f" {n}_qca = PREREAD ? {n}_mem[9'h120] : 18'h0; end")
        o.append(f"wire [8:0] {n}_ada = {{{', '.join(reversed([sig(p) for p in m['addr']]))}}}; wire [17:0] {n}_dia = {{{', '.join(reversed([sig(p) for p in m['data']]))}}};")
        inv = {p_: j for j, (t_, p_) in WORD_WIRE.items() if TILES[t_] == t}
        bits = ", ".join((f"ovr_en ? ovr_word[{inv[k]}] : {n}_dia[{k}]" if k in inv else f"{n}_dia[{k}]") for k in range(17, -1, -1))
        o.append(f"wire [17:0] {n}_dib = {{{bits}}};")
        o.append(f"always @(posedge clk) begin if ((WEMODE != 0 && cyc >= WEHOLD) && (WEMODE == 2 ? !{m['we_b']} : {m['we_b']})) begin {n}_mem[{n}_ada] <= {n}_dib; {n}_qca <= {n}_dib; end else {n}_qca <= {n}_mem[{n}_ada]; end")
        o.append(f"assign {n}_o = {{18'b0, {n}_qca}};")
    o.append(f"assign af3_drv = {io['drv']}; assign af3_oe = {io['oe']};")
    o.append(f"assign ramaddr = m9k_7_85_ada; assign ramwe = (WEMODE != 0 && cyc >= WEHOLD) && (WEMODE == 2 ? !{ta['we_b']} : {ta['we_b']});")
    rd = ", ".join(f"m9k_{TILES[WORD_WIRE[j][0]]}_o[{WORD_WIRE[j][1]}]" for j in range(31, -1, -1))
    wd = ", ".join(f"m9k_{TILES[WORD_WIRE[j][0]]}_dib[{WORD_WIRE[j][1]}]" for j in range(31, -1, -1))
    o.append(f"assign ramrd = {{{rd}}}; assign ramwd = {{{wd}}};")
    o.append("endmodule")
    open(os.path.join(OUT, "engine.v"), "w").write("\n".join(o) + "\n")
    ffs = {n: i for i, n in enumerate(reversed(eng))}      # ffvec bit index (msb = first)
    json.dump({"ffs": eng, "ffvec_bit": ffs, "luts": len(luts), "leaves": leaves}, open(os.path.join(OUT, "engine.json"), "w"), indent=1)
    log.info("[V] cone: %d FFs, %d LUT/carry cells, leaves %s", len(eng), len(luts), leaves)


def build(gens=(), obj="obj"):
    cmd = ["verilator", "--cc", "--exe", "--build", "-O1", "-Wno-fatal", "-Wno-lint", "-Wno-style", "--top-module", "engine", "-Mdir", os.path.join(OUT, obj),
           os.path.join(OUT, "engine.v"), os.path.join(REPO, "scripts", "af3_engine_tb.cpp"), "-o", "Vengine"] + [f"-G{g}" for g in gens]
    log.info("run %s", " ".join(cmd))
    r = subprocess.run(cmd, capture_output=True, text=True)
    log.info("%s", (r.stdout + r.stderr)[-3000:])
    if r.returncode:
        raise SystemExit("verilator failed")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["extract", "build"])
    ap.add_argument("--nl", default=os.path.join(REPO, "tmp", "dji_microcode", "build", "nl.pkl"))
    ap.add_argument("-G", action="append", default=[], help="top-level parameter NAME=VAL (PREREAD, WEMODE)")
    ap.add_argument("--obj", default="obj", help="build dir under tmp/af3")
    a = ap.parse_args()
    os.makedirs(os.path.dirname(LOG), exist_ok=True)
    logging.basicConfig(level=logging.INFO, format="%(message)s", handlers=[logging.FileHandler(LOG, "a"), logging.StreamHandler()])
    if a.cmd == "extract":
        extract(pickle.load(open(a.nl, "rb")))
    else:
        build(a.G, a.obj)


if __name__ == "__main__":
    main()
