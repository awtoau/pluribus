"""M9K port-input mapper tables, from code (#165, #169): (explicit RAM mode = port width, group index) -> (port source type, port index).

Table `ram_mapper_table.json` generated by scripts/cycloneiv_ram_mapper.py (emulated family-14 MEAB blocks of the libcomp_asmram ASM_RAM_MS_* constructors,
read by ASM_RAM_MS_INPUT_MAPPER::look_up_port_source@0x661b0; mode from calculate_explicit_mode@0x65ddc).
Port index space: data pins DATAIN idx 0..17 (parity lane idx 8 / 17 skipped by modes that exclude it: x16 and x32), address pins idx 0..12.
"""
import json
import os

PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "ram_mapper_table.json")
DATA_TYPE = 3       # source: RAM_MS_DATA_INPUT entries of every width mode with a full data lane: type 3 idx k = DATAIN[k]
_t = []


def table():
    if not _t:
        _t.append(json.load(open(PATH)))
    return _t[0]


def mode_of(width):
    return table()["width_mode"][str(width)]


def entries(group, width):
    """[(gi, type, idx)] of one group class at one port width."""
    m = mode_of(width)
    return [(gi, ty, ix) for mo, gi, ty, ix in table()["groups"][group] if mo == m]


def data_gi(width):
    """DATAIN idx -> RAM_MS_DATA_INPUT gi."""
    return {ix: gi for gi, ty, ix in entries("RAM_MS_DATA_INPUT", width) if ty == DATA_TYPE}


def data_idx(width):
    """Sorted DATAIN pin indices used by the width (logical bit k = k-th entry)."""
    return sorted(data_gi(width))


def addr_sources(width):
    """address pin idx -> [(group class, gi)] over the write-address group and the data groups that carry address bits at this width."""
    out = {}
    for gi, ty, ix in entries("RAM_MS_DATA_INPUT", width):
        if ty != DATA_TYPE:
            out.setdefault(ix, []).append(("RAM_MS_DATA_INPUT", gi))
    for gi, ty, ix in entries("RAM_MS_WRITE_ADDRESS_INPUT", width):
        out.setdefault(ix, []).append(("RAM_MS_WRITE_ADDRESS_INPUT", gi))
    return out


def byte_enable_gi(width):
    """byte-enable idx -> RAM_MS_BYTE_ENABLE_INPUT gi."""
    return {ix: gi for gi, ty, ix in entries("RAM_MS_BYTE_ENABLE_INPUT", width)}


# source: explicit RAM modes of the true dual port constructors (ram_mapper_table.json: groups of modes 6..9, 16..18 carry type-4 DATA_INPUT_B and
#         type-6 READ_ADDRESS entries); mode = width: x1 6, x2 7, x4 8, x8 9, x9 16, x16 17, x18 18
TDP_MODE = {1: 6, 2: 7, 4: 8, 8: 9, 9: 16, 16: 17, 18: 18}
TYPE_DATA_A, TYPE_DATA_B, TYPE_ADDR_A, TYPE_ADDR_B = 3, 4, 5, 6


def entries_mode(group, mode):
    """[(gi, type, idx)] of one group class at an explicit mode number."""
    return [(gi, ty, ix) for mo, gi, ty, ix in table()["groups"][group] if mo == mode]
