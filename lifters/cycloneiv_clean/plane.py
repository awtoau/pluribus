"""Cyclone IV GX (EP4CGX150) CRAM geometry and the sof -> rbf closed form.  Pure functions only.

Accepted facts: docs/cycloneiv-clean-pipeline.md A4-A6.  `address_to_plane` = sof identity then A5 (#165).
CANDIDATES keeps the rejected `lut_law_preserved` alongside it for the oracles.
Plane cell = (r, j, k): CRAM frame r (0..6153), data byte j (1..793), bit k (0..7).
"""
import os

import numpy as np

REPO = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
TABLES_PATH = os.path.join(REPO, "databases", "cycloneiv", "sof2rbf_mask.npz")

# source: A6 geometry (EP4CGX150) = sof tag-17 section length + pcf/hdr frame_bits (docs/cycloneiv-bitstream.md)
FRAMES = 6154                   # CRAM frames
ROWS = 793                      # data bytes per frame and lane
LANES = 8
BITS_PER_FRAME = ROWS * LANES   # 6344
N_BITS = FRAMES * BITS_PER_FRAME  # 39,040,976
# source: A4 rbf layout read from quartus_cpf output (header bytes, frames before CRAM, bytes/frame = pad + 793 data + 2 crc)
RBF_HEADER = 32
RBF_PRE_FRAMES = 37
RBF_FRAME_BYTES = 796


class TablesMissing(FileNotFoundError):
    pass


class Tables:
    """Per-die mirrored 256-frame blocks and the cell mask.  Local file, regenerated by scripts/cycloneiv_sof2rbf_tables.py."""

    def __init__(self, blocks, mask):
        self.blocks = np.asarray(blocks, np.int64)
        self.mask = np.asarray(mask, bool)          # [ROWS][LANES], index [j - 1, k]
        if self.mask.shape != (ROWS, LANES):
            raise ValueError(f"mask shape {self.mask.shape}")


_cache = {}


def load_tables(path=TABLES_PATH):
    if path not in _cache:
        if not os.path.exists(path):
            raise TablesMissing(f"{path} missing; run scripts/cycloneiv_sof2rbf_tables.py")
        z = np.load(path)
        _cache[path] = Tables(z["blocks"], z["mask"])
    return _cache[path]


def sof_to_fv(i):
    """sof data bit index -> (sof frame s, v)."""
    i = np.asarray(i, np.int64)
    return i % FRAMES, i // FRAMES


def v_to_jk(v):
    """v -> (byte j, bit k): k = v div 793, j = 793 - v mod 793."""
    v = np.asarray(v, np.int64)
    return ROWS - v % ROWS, v // ROWS


def jk_to_v(j, k):
    j, k = np.asarray(j, np.int64), np.asarray(k, np.int64)
    return k * ROWS + ROWS - j


def sof_to_rbf(i, tables=None):
    """A5: sof data bit index -> (r, j, k).  Frame 6153 - s; cells selected by the mask inside a block are
    mirrored within it (r = r0 + s - (6153 - r0 - 255))."""
    t = tables or load_tables()
    s, v = sof_to_fv(i)
    j, k = v_to_jk(v)
    r = FRAMES - 1 - s
    m = t.mask[j - 1, k]
    for b in t.blocks.tolist():
        inb = m & (s >= FRAMES - 1 - b - 255) & (s <= FRAMES - 1 - b)
        r = np.where(inb, b + (s - (FRAMES - 1 - b - 255)), r)
    return r, j, k


def rbf_bit_offset(r, j, k):
    """Bit offset of a plane cell in the rbf file (A4/A5: LSB-first within the byte)."""
    r, j, k = (np.asarray(a, np.int64) for a in (r, j, k))
    return (RBF_HEADER + (RBF_PRE_FRAMES + r) * RBF_FRAME_BYTES) * 8 + 8 * j + k


def plane_frame(r):
    """rbf file frame index of CRAM frame r."""
    return np.asarray(r, np.int64) + RBF_PRE_FRAMES


def plane_v(j, k):
    """Vertical position, lane 7 first: 793 * (7 - k) + j.  Equals 6344 - v for the sof v of the same cell."""
    j, k = np.asarray(j, np.int64), np.asarray(k, np.int64)
    return ROWS * (LANES - 1 - k) + j


def plane_v_to_jk(pv):
    """Inverse of plane_v for 1 <= pv <= 6344."""
    pv = np.asarray(pv, np.int64) - 1
    return pv % ROWS + 1, LANES - 1 - pv // ROWS


# ---- raw asm address -> plane cell ------------------------------------------------------------------------

def address_to_plane(addr, tables=None):
    """Raw asm address -> (r, j, k): the address is the sof data bit index (A4), then A5.
    Validated: routing arcs (O2) and, with the LAB LUT formula's in-column sign negated, all LUT cells (O1, #165)."""
    return sof_to_rbf(addr, tables)


def _cand_sof_identity_reversed(addr, tables=None):
    """Raw address taken as the sof data bit index, then A5."""
    return sof_to_rbf(addr, tables)


def _cand_lut_law_preserved(addr, tables=None):
    """Plane frame = asm frame + 43 (file frame), v mirrored: pv = 6344 - asm v.  r = -1 outside 0..6153."""
    a = np.asarray(addr, np.int64)
    s, v = sof_to_fv(a)
    j, k = v_to_jk(v)                      # same cell bit/byte split as A5
    r = s + 43 - RBF_PRE_FRAMES
    return np.where((r >= 0) & (r < FRAMES), r, -1), j, k


CANDIDATES = {
    "sof_identity_reversed": _cand_sof_identity_reversed,
    "lut_law_preserved": _cand_lut_law_preserved,
}
