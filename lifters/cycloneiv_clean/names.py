"""RCF element names (A7): `TYPE:X<x>Y<y>S<z>I<index>` -> exact key over (type, x, y, z, index).  No aliasing, no fallback.

Type string -> routing.ddb element enum comes from names_table.json (generated by scripts/cycloneiv_clean_names_table.py,
per-entry `source`).  Types with enum null are unmapped and raise.
"""
import json
import os
import re

from . import ddb

NAME = re.compile(r"\b([A-Z][A-Z0-9_]*):X(\d+)Y(\d+)S(\d+)I(\d+)\b")
TABLE_PATH = os.path.join(os.path.dirname(os.path.abspath(__file__)), "names_table.json")
_table = {}


class UnmappedType(KeyError):
    pass


def table():
    if not _table:
        with open(TABLE_PATH) as f:
            _table.update(json.load(f))
    return _table


def entries():
    """type string -> table entry (enum may be null)."""
    return {e["type"]: e for e in table()["types"]}


def enum_of(type_name):
    e = entries().get(type_name)
    if e is None or e["enum"] is None:
        raise UnmappedType(type_name)
    return e["enum"]


def enums(status=("derived", "consistent-few-edges")):
    """type string -> enum for the entries whose status is in `status`."""
    return {t: e["enum"] for t, e in entries().items() if e["status"] in status}


def key_of(name):
    """(type, x, y, z, index) -> int64 key of ddb.element_key; raises UnmappedType."""
    t, x, y, z, i = name
    return ddb.element_key(enum_of(t), x, y, z, i)


def rcf_names(path):
    """Distinct (type, x, y, z, index) tuples of one routing.rcf."""
    with open(path) as f:
        text = f.read()
    return sorted({(m[1], int(m[2]), int(m[3]), int(m[4]), int(m[5])) for m in NAME.finditer(text)})
